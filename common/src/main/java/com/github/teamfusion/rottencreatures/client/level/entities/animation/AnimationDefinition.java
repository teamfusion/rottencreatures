package com.github.teamfusion.rottencreatures.client.level.entities.animation;

public class AnimationDefinition {
    protected static float toRadians(float degrees) {
        return (float) Math.toRadians(degrees);
    }

    protected static float toRadians(double degrees) {
        return (float) Math.toRadians(degrees);
    }

    protected static float toRadians(int value) {
        return (float) Math.toRadians(value);
    }
}